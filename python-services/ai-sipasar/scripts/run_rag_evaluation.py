"""RAG evaluation baseline (blueprint section 33): Recall@K + source precision.

Usage:
    DATABASE_URL=... GEMINI_API_KEY=... python -m scripts.run_rag_evaluation \
        --umkm-id <uuid> --eval-set eval_cases.jsonl [--out report.md]

Each JSONL case:
    {"query": "...", "expected_chunk_ids": ["<uuid>", ...]}

Output: markdown report with per-case metrics, macro Recall@K, macro source
precision, and a tenant-leakage check (every retrieved chunk must belong to
the target tenant).
"""

from __future__ import annotations

import argparse
import asyncio
import json
import statistics
import sys
from pathlib import Path

from sipromo.application.ports.retriever import RetrievalQuery
from sipromo.bootstrap.container import Container
from sipromo.bootstrap.settings import Settings


async def run(umkm_id: str, eval_set: Path, out: Path, k: int) -> int:
    if not eval_set.is_file():  # noqa: ASYNC240 - local eval file
        print(f"eval set not found: {eval_set}", file=sys.stderr)
        return 2

    lines = eval_set.read_text(encoding="utf-8").splitlines()  # noqa: ASYNC240 - local eval file
    cases = [json.loads(line) for line in lines if line.strip()]
    if not cases:
        print("eval set is empty", file=sys.stderr)
        return 2

    container = Container(Settings())
    container.build_use_cases()
    retriever = container.retriever
    if retriever is None:
        print("retriever unavailable; AI provider must be configured", file=sys.stderr)
        return 2

    rows = []
    for i, case in enumerate(cases, start=1):
        query = RetrievalQuery(
            umkm_id=umkm_id,
            query=case["query"],
            top_k_vector=k,
            top_k_lexical=k,
            min_score=container.settings.rag_min_score,
        )
        chunks = await retriever.retrieve(query)
        found = {c.chunk_id for c in chunks}
        expected = set(case.get("expected_chunk_ids", []))
        leaked = [c for c in chunks if c.umkm_id != umkm_id]

        recall = len(found & expected) / len(expected) if expected else None
        precision = len(found & expected) / len(found) if found else 0.0
        rows.append(
            {
                "case": i,
                "query": case["query"],
                "retrieved": len(found),
                "expected": len(expected),
                "recall_at_k": recall,
                "source_precision": precision,
                "tenant_leakage": len(leaked),
            }
        )

    recalls = [r["recall_at_k"] for r in rows if r["recall_at_k"] is not None]
    precisions = [r["source_precision"] for r in rows]
    total_leakage = sum(r["tenant_leakage"] for r in rows)
    summary = {
        "cases": len(rows),
        "macro_recall_at_k": statistics.fmean(recalls) if recalls else None,
        "macro_source_precision": statistics.fmean(precisions),
        "tenant_leakage": total_leakage,
        "k": k,
    }

    lines = [
        "# RAG Evaluation Baseline",
        "",
        "- Date: generated by `python -m scripts.run_rag_evaluation`",
        f"- Tenant: `{umkm_id}`",
        f"- K: {k}",
        f"- Cases: {summary['cases']}",
        "",
        "## Summary",
        "",
        "| Metric | Value |",
        "| --- | --- |",
        f"| Macro Recall@K | {summary['macro_recall_at_k']:.3f} |"
        if summary["macro_recall_at_k"] is not None
        else "| Macro Recall@K | n/a (no ground-truth cases) |",
        f"| Macro Source Precision | {summary['macro_source_precision']:.3f} |",
        f"| Tenant Leakage | {summary['tenant_leakage']} (must be 0) |",
        "",
        "## Per-Case",
        "",
        "| Case | Query | Retrieved | Expected | Recall@K | Source Precision | Leakage |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for r in rows:
        lines.append(
            f"| {r['case']} | {r['query'][:60]} | {r['retrieved']} | {r['expected']} "
            f"| {r['recall_at_k']:.3f}"
            if r["recall_at_k"] is not None
            else f"| {r['case']} | {r['query'][:60]} | {r['retrieved']} | {r['expected']} | n/a "
            f"| {r['source_precision']:.3f} | {r['tenant_leakage']} |"
        )
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")  # noqa: ASYNC240 - local eval file
    print(f"report written to {out}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--umkm-id", required=True, help="tenant (UMKM) UUID")
    parser.add_argument("--eval-set", required=True, help="JSONL eval cases")
    parser.add_argument("--out", default="docs/evaluation_report.md")
    parser.add_argument("--k", type=int, default=5, help="top-K per signal")
    args = parser.parse_args()

    container = Container(Settings())
    if not container.settings.gemini_configured:
        print("GEMINI_API_KEY is required for embeddings", file=sys.stderr)
        return 2

    return asyncio.run(run(args.umkm_id, Path(args.eval_set), Path(args.out), args.k))


if __name__ == "__main__":
    sys.exit(main())
